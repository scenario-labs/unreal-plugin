#include "ScenarioContentBrowserFilter.h"

#include "ContentBrowserItem.h"
#include "FrontendFilterBase.h"
#include "ScenarioProvenance.h"
#include "ScenarioSubsystem.h"

#define LOCTEXT_NAMESPACE "ScenarioContentBrowserFilter"

namespace
{
	/** Matches assets listed in the project's provenance index, so no asset is loaded to filter. */
	class FScenarioFrontendFilter : public FFrontendFilter
	{
	public:
		explicit FScenarioFrontendFilter(TSharedPtr<FFrontendFilterCategory> InCategory)
			: FFrontendFilter(InCategory)
		{
		}

		virtual FString GetName() const override { return TEXT("GeneratedByScenario"); }
		virtual FText GetDisplayName() const override { return LOCTEXT("Name", "Generated by Scenario"); }
		virtual FText GetToolTipText() const override { return LOCTEXT("Tip", "Assets this project imported from Scenario."); }
		virtual FLinearColor GetColor() const override { return FLinearColor::White; }

		virtual bool PassesFilter(FAssetFilterType InItem) const override
		{
			const UScenarioSubsystem* Subsystem = UScenarioSubsystem::Get();
			FAssetData Asset;
			return Subsystem && InItem.Legacy_TryGetAssetData(Asset) && Subsystem->Provenance().Contains(Asset.GetObjectPathString());
		}
	};
}

void UScenarioContentBrowserFilterExtension::AddFrontEndFilterExtensions(TSharedPtr<FFrontendFilterCategory> DefaultCategory, TArray<TSharedRef<FFrontendFilter>>& InOutFilterList) const
{
	const TSharedPtr<FFrontendFilterCategory> Category = MakeShared<FFrontendFilterCategory>(LOCTEXT("Category", "Scenario"), LOCTEXT("CategoryTip", "Scenario filters"));
	InOutFilterList.Add(MakeShared<FScenarioFrontendFilter>(Category));
}

#undef LOCTEXT_NAMESPACE
